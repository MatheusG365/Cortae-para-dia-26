"""Additive local management tables. Run only after a verified backup."""
from application import conectar_banco
from .schema_utils import criar_tabela, criar_sequence


TABLES = {
    'GESTAO_CLIENTE': '''CREATE TABLE GESTAO_CLIENTE (
        ID_BARBEARIA INTEGER NOT NULL REFERENCES USUARIO(ID_USUARIO),
        ID_USUARIO INTEGER NOT NULL REFERENCES USUARIO(ID_USUARIO),
        OBSERVACOES BLOB SUB_TYPE TEXT, PREFERENCIAS BLOB SUB_TYPE TEXT,
        ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        PRIMARY KEY(ID_BARBEARIA,ID_USUARIO))''',
    'GESTAO_CATEGORIA': '''CREATE TABLE GESTAO_CATEGORIA (
        ID_CATEGORIA INTEGER NOT NULL PRIMARY KEY,
        ID_BARBEARIA INTEGER NOT NULL REFERENCES USUARIO(ID_USUARIO),
        NOME VARCHAR(100) NOT NULL, TIPO VARCHAR(10) NOT NULL CHECK(TIPO IN ('entrada','saida')),
        ATIVO SMALLINT DEFAULT 1 NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)''',
    'GESTAO_LANCAMENTO': '''CREATE TABLE GESTAO_LANCAMENTO (
        ID_LANCAMENTO INTEGER NOT NULL PRIMARY KEY,
        ID_BARBEARIA INTEGER NOT NULL REFERENCES USUARIO(ID_USUARIO),
        ID_CATEGORIA INTEGER REFERENCES GESTAO_CATEGORIA(ID_CATEGORIA),
        TIPO VARCHAR(10) NOT NULL CHECK(TIPO IN ('entrada','saida')),
        DESCRICAO VARCHAR(500) NOT NULL, VALOR DECIMAL(12,2) NOT NULL CHECK(VALOR>0),
        VENCIMENTO DATE NOT NULL, STATUS VARCHAR(10) NOT NULL CHECK(STATUS IN ('pendente','pago','cancelado')),
        DATA_PAGAMENTO DATE, CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)''',
    'GESTAO_RECEBIMENTO': '''CREATE TABLE GESTAO_RECEBIMENTO (
        ID_RECEBIMENTO INTEGER NOT NULL PRIMARY KEY,
        ID_AGENDAMENTO INTEGER NOT NULL REFERENCES AGENDAMENTO(ID_AGENDAMENTO),
        ID_BARBEARIA INTEGER NOT NULL REFERENCES USUARIO(ID_USUARIO),
        ID_FINANCEIRO INTEGER NOT NULL UNIQUE REFERENCES FINANCEIRO(ID_FINANCEIRO),
        FORMA VARCHAR(15) NOT NULL CHECK(FORMA IN ('dinheiro','cartao','pix_manual')),
        VALOR DECIMAL(12,2) NOT NULL CHECK(VALOR>0), DATA_PAGAMENTO DATE NOT NULL,
        OBSERVACAO VARCHAR(500), ID_USUARIO_RESPONSAVEL INTEGER NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)''',
    'GESTAO_COMISSAO_PAGAMENTO': '''CREATE TABLE GESTAO_COMISSAO_PAGAMENTO (
        ID_PAGAMENTO INTEGER NOT NULL PRIMARY KEY,
        ID_AGENDAMENTO INTEGER NOT NULL REFERENCES COMISSAO_ATENDIMENTO(ID_AGENDAMENTO),
        ID_BARBEARIA INTEGER NOT NULL REFERENCES USUARIO(ID_USUARIO),
        ID_LANCAMENTO INTEGER NOT NULL UNIQUE REFERENCES GESTAO_LANCAMENTO(ID_LANCAMENTO),
        VALOR DECIMAL(12,2) NOT NULL CHECK(VALOR>0), DATA_PAGAMENTO DATE NOT NULL,
        OBSERVACAO VARCHAR(500), ID_USUARIO_RESPONSAVEL INTEGER NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)''',
    'GESTAO_OPERACAO': '''CREATE TABLE GESTAO_OPERACAO (
        ID_BARBEARIA INTEGER NOT NULL REFERENCES USUARIO(ID_USUARIO),
        CHAVE VARCHAR(64) NOT NULL, TIPO VARCHAR(20) NOT NULL,
        ID_REFERENCIA INTEGER NOT NULL, HASH_PEDIDO CHAR(64) NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        PRIMARY KEY(ID_BARBEARIA,CHAVE))''',
}


def migrar_gestao():
    con = conectar_banco(); cur = con.cursor()
    try:
        for name, ddl in TABLES.items():
            criar_tabela(cur, name, ddl, con)
        for seq in ('SEQ_GESTAO_CATEGORIA','SEQ_GESTAO_LANCAMENTO','SEQ_GESTAO_RECEBIMENTO','SEQ_GESTAO_COMISSAO_PAG'):
            criar_sequence(cur, seq, con)
        con.commit()
    except Exception:
        con.rollback(); raise
    finally:
        cur.close(); con.close()
